    private static void migrateLegacyConfig(Configuration config) {
        final String migrationCategory = "internal.migration";
        final String migrationKey = "configMigrationVersion";
        if (config.get(migrationCategory, migrationKey, 0).getInt() >= 1) return;

        copyCategory(config, "OreSpawnIDS", "general.ids");
        copyCategory(config, "OreSpawnTWEAKS", "general.tweaks");
        copyCategory(config, "OreSpawnWEAPONS", "balance.weapons");
        copyCategory(config, "OreSpawnARMOR", "balance.armor");
        copyCategory(config, "OreSpawnORES", "worldgen.ores");

        if (config.hasCategory("OreSpawnMOBS")) {
            for (java.util.Map.Entry<String, net.minecraftforge.common.config.Property> entry
                : config.getCategory("OreSpawnMOBS").getValues().entrySet()) {
                String key = entry.getKey();
                String target = key.endsWith("_health") || key.endsWith("_attack") || key.endsWith("_defense")
                    ? "mobs.stats" : "mobs.enabled";
                copyProperty(config, target, key, entry.getValue());
            }
        }

        config.get(migrationCategory, migrationKey, 1).set(1);
    }

    private static void copyCategory(Configuration config, String source, String target) {
        if (!config.hasCategory(source)) return;
        for (java.util.Map.Entry<String, net.minecraftforge.common.config.Property> entry
            : config.getCategory(source).getValues().entrySet()) {
            copyProperty(config, target, entry.getKey(), entry.getValue());
        }
    }

    private static void copyProperty(Configuration config, String category, String key,
                                     net.minecraftforge.common.config.Property source) {
        config.get(category, key, source.getInt()).set(source.getInt());
    }


